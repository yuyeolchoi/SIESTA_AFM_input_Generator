"""Prepare CP2K job folders and a SLURM array script from enumerated spin files."""

from __future__ import annotations

import csv
import re
from pathlib import Path
from typing import Any, Mapping, Sequence

from .cp2k_writer import CP2KInputResult, render_cp2k_input
from .io import parse_dm_init_spin
from .structure import Structure


_TOKEN_RE = re.compile(r"^[A-Za-z0-9_.+-]+$")
_PATH_RE = re.compile(r"^[A-Za-z0-9_./+-]+$")


def _token(value: str, label: str) -> str:
    text = str(value).strip()
    if not text or not _TOKEN_RE.match(text):
        raise ValueError(f"{label} must be a plain token (letters, digits, _ . + -): {value!r}")
    return text


def _path_token(value: str, label: str) -> str:
    text = str(value).strip()
    if not text or not _PATH_RE.match(text):
        raise ValueError(f"{label} must be a plain path without spaces or shell characters: {value!r}")
    return text


def render_cp2k_slurm_script(
    job_count: int,
    *,
    job_name: str = "cp2k_afm",
    partition: str | None = None,
    ntasks: int = 8,
    cpus_per_task: int = 1,
    walltime: str = "04:00:00",
    memory: str | None = None,
    max_concurrent: int | None = None,
    cp2k_env: str | None = None,
    module: str | None = None,
    cp2k_exe: str = "cp2k.psmp",
    mpirun: str = "/usr/bin/mpirun",
    strip_nvhpc: bool = True,
    input_name: str = "input.inp",
) -> str:
    """Render a SLURM array script that runs one CP2K job folder per task.

    The script follows the conventions verified on the group's CPU build:
    one MPI rank per core with ``OMP_NUM_THREADS=1``, NVHPC removed from the
    environment, ``cp2k_env`` sourced instead of a module, a preflight that
    refuses to start on a mixed library stack, a per-job output name because
    CP2K appends to an existing output file, and an ``exit_code`` file that
    ``collect-results`` reads.
    """

    if job_count < 1 or ntasks < 1 or cpus_per_task < 1:
        raise ValueError("job count, ntasks, and cpus per task must be positive")
    if max_concurrent is not None and max_concurrent < 1:
        raise ValueError("maximum concurrent jobs must be positive")
    if not re.fullmatch(r"\d{1,3}:\d{2}:\d{2}", walltime):
        raise ValueError("walltime must use HH:MM:SS")
    _, minutes, seconds = (int(field) for field in walltime.split(":"))
    if minutes >= 60 or seconds >= 60:
        raise ValueError("walltime minutes and seconds must be below 60")
    if cp2k_env is None and module is None:
        raise ValueError("provide --cp2k-env (source file) or --module to load CP2K")
    name = _token(job_name, "job name")
    exe = _path_token(cp2k_exe, "CP2K executable")
    launcher = _path_token(mpirun, "mpirun")
    input_file = _token(input_name, "input file name")
    array = f"1-{job_count}" + (f"%{max_concurrent}" if max_concurrent is not None else "")

    lines = [
        "#!/bin/bash",
        f"#SBATCH --job-name={name}",
        f"#SBATCH --ntasks={ntasks}",
        f"#SBATCH --cpus-per-task={cpus_per_task}",
        f"#SBATCH --time={walltime}",
        f"#SBATCH --array={array}",
        "#SBATCH --output=%x_%A_%a.out",
        "#SBATCH --error=%x_%A_%a.err",
    ]
    if partition:
        lines.insert(2, f"#SBATCH --partition={_token(partition, 'partition')}")
    if memory:
        lines.insert(len(lines) - 2, f"#SBATCH --mem={_token(memory, 'memory')}")
    lines.append("# --time and --mem are estimates, not measurements; adjust after the first run.")
    lines.extend(
        [
            "",
            "# Generated by siesta-afm prepare-cp2k-array. One array task = one job folder.",
            "set -euo pipefail",
            'ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
            'TASK_INDEX="${SLURM_ARRAY_TASK_ID}"',
            'FOLDER="$(sed -n "${TASK_INDEX}p" "$ROOT/folders.list")"',
            'if [ -z "$FOLDER" ] || [ ! -d "$ROOT/$FOLDER" ]; then',
            '  echo "Invalid array index $TASK_INDEX: $FOLDER" >&2',
            "  exit 2",
            "fi",
            'cd "$ROOT/$FOLDER"',
            "",
            "module purge",
        ]
    )
    if strip_nvhpc:
        lines.extend(
            [
                "# NVHPC compilers/MPI are not supported by the CP2K toolchain build; keep one MPI.",
                "strip_nvhpc() { printf '%s' \"$1\" | tr ':' '\\n' | grep -v 'hpc_sdk' | paste -sd ':' -; }",
                'export PATH="$(strip_nvhpc "$PATH")"',
                'export LD_LIBRARY_PATH="$(strip_nvhpc "${LD_LIBRARY_PATH:-}")"',
            ]
        )
    if module:
        lines.append(f"module load {_path_token(module, 'module')}")
    if cp2k_env:
        env_path = _path_token(cp2k_env, "cp2k_env path")
        lines.extend(
            [
                "# The executable has no RPATH; cp2k_env provides libcp2k.so, MPI, ELPA, ScaLAPACK.",
                "set +eu",
                f'source "{env_path}"',
                "set -eu",
            ]
        )
    lines.extend(
        [
            "export OMP_NUM_THREADS=1",
            f'CP2K_BIN="$(command -v {exe} || true)"',
            'if [ -z "$CP2K_BIN" ]; then',
            f'  echo "refusing to start: {exe} not found in PATH" >&2',
            "  exit 3",
            "fi",
            "",
            "# Preflight: refuse a wrong binary or a mixed library stack.",
        ]
    )
    if cp2k_env:
        lines.extend(
            [
                'case "$CP2K_BIN" in',
                "  */install/bin/*) ;;",
                '  *) echo "refusing to start: $CP2K_BIN is not under install/bin" >&2; exit 3 ;;',
                "esac",
            ]
        )
    lines.extend(
        [
            'if ldd "$CP2K_BIN" | grep -q "not found"; then',
            '  echo "refusing to start: unresolved shared libraries" >&2',
            '  ldd "$CP2K_BIN" | grep "not found" >&2',
            "  exit 3",
            "fi",
            'if ldd "$CP2K_BIN" | grep -q "hpc_sdk"; then',
            '  echo "refusing to start: NVHPC libraries resolve in the stack" >&2',
            "  exit 3",
            "fi",
            'if [ "$(ldd "$CP2K_BIN" | grep -c "libmpi.so.40")" -gt 1 ]; then',
            '  echo "refusing to start: more than one libmpi.so.40 resolves" >&2',
            "  exit 3",
            "fi",
            "",
            "# CP2K appends to an existing output file; give every job its own name.",
            'OUT="cp2k_${SLURM_JOB_ID}.out"',
            "set +e",
            f'{launcher} -np "$SLURM_NTASKS" --bind-to core --map-by core "$CP2K_BIN" -i {input_file} -o "$OUT"',
            "status=$?",
            "set -e",
            "printf '%s\\n' \"$status\" > exit_code",
            'exit "$status"',
            "",
        ]
    )
    return "\n".join(lines)


def prepare_cp2k_array(
    structure: Structure,
    configs_dir: str | Path,
    output_dir: str | Path,
    *,
    magnetic_species: Sequence[str],
    writer_options: Mapping[str, Any] | None = None,
    job_script: bool = True,
    job_options: Mapping[str, Any] | None = None,
) -> tuple[list[Path], list[str]]:
    """Write one CP2K input per enumerated spin file plus a SLURM array script.

    ``configs_dir`` is an ``enumerate`` output directory (``manifest.csv`` and
    ``afm_*.fdf``).  Each job folder ``<config_id>_<method>`` receives
    ``input.inp``; ``folders.list`` and ``cp2k_manifest.csv`` describe the
    array; ``run_cp2k_array.sbatch`` is written unless ``job_script`` is false.
    Returns the folders and the distinct writer warnings.
    """

    configs = Path(configs_dir)
    destination = Path(output_dir)
    manifest_path = configs / "manifest.csv"
    if not manifest_path.is_file():
        raise FileNotFoundError(f"configuration manifest not found: {manifest_path}")
    options = dict(writer_options or {})
    project_prefix = options.pop("project_name", None)
    wanted = {item.lower() for item in magnetic_species}
    destination.mkdir(parents=True, exist_ok=True)
    folders: list[Path] = []
    warnings: list[str] = []
    manifest_rows: list[dict[str, object]] = []
    with manifest_path.open(newline="", encoding="utf-8-sig") as handle:
        for row in csv.DictReader(handle):
            config_id = row["config_id"]
            method = row["method"]
            spin_path = configs / row["file"]
            spins: dict[int, float] = {}
            for index, value in parse_dm_init_spin(spin_path):
                if not 1 <= index <= len(structure):
                    raise ValueError(
                        f"{spin_path.name}: DM.InitSpin atom index out of range: {index}"
                    )
                if value != 0 and structure.symbols[index - 1].lower() not in wanted:
                    raise ValueError(
                        f"{spin_path.name}: nonzero spin on atom {index} "
                        f"({structure.symbols[index - 1]}) outside --magnetic-species"
                    )
                spins[index - 1] = float(value)
            result: CP2KInputResult = render_cp2k_input(
                structure,
                spins,
                method=method,
                magnetic_species=magnetic_species,
                project_name=(
                    f"{project_prefix}_{config_id}" if project_prefix else f"afm_{config_id}"
                ),
                **options,
            )
            folder = destination / f"{config_id}_{method}"
            folder.mkdir(parents=True, exist_ok=True)
            (folder / "input.inp").write_text(result.text, encoding="utf-8")
            folders.append(folder)
            for warning in result.warnings:
                if warning not in warnings:
                    warnings.append(warning)
            manifest_rows.append(
                {
                    "config_id": config_id,
                    "method": method,
                    "folder": folder.name,
                    "spin_file": row["file"],
                    "multiplicity": result.multiplicity,
                    "charge": result.charge,
                    "kinds": " ".join(
                        f"{kind.label}={kind.magnetization:g}" for kind in result.kinds
                    ),
                }
            )
    if not folders:
        raise ValueError("configuration manifest contains no rows")
    (destination / "folders.list").write_text(
        "\n".join(folder.name for folder in folders) + "\n", encoding="utf-8"
    )
    with (destination / "cp2k_manifest.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(manifest_rows[0]))
        writer.writeheader()
        writer.writerows(manifest_rows)
    if job_script:
        script = render_cp2k_slurm_script(len(folders), **dict(job_options or {}))
        (destination / "run_cp2k_array.sbatch").write_text(script, encoding="utf-8")
    return folders, warnings
